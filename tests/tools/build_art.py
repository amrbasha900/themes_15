#!/usr/bin/env python3
"""Bundles the editable SVG backgrounds into themate/public/js/core/art_svgs.js.

Frappe's esbuild has no .svg loader, and a bare /assets file would sit behind
nginx's one-year cache, so the art ships inside the hashed bundle as strings.
Edit the .svg, then:  python3 tests/tools/build_art.py && bench build --app themate
--check exits 1 when the bundle is stale (tests/sidebar-art.test.js runs it).
"""
import json
import re
import sys
from pathlib import Path

PUBLIC = Path(__file__).resolve().parents[2] / "themate" / "public"
SOURCES = {"sidebar": "frappe_sidebar_editable.svg", "greeting": "frappe_greeting_card_waves_only.svg"}
OUT = PUBLIC / "js" / "core" / "art_svgs.js"


def minify(svg):
	svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
	svg = re.sub(r"<(title|desc)\b.*?</\1>", "", svg, flags=re.S)
	svg = re.sub(r"/\*.*?\*/", "", svg, flags=re.S)
	svg = re.sub(r'\s(role|aria-labelledby)="[^"]*"', "", svg)
	# the card's own CSS radius rounds it, at whatever corner preset is chosen
	svg = re.sub(r'\sclip-path="url\(#cardClip\)"', "", svg)
	svg = re.sub(r"<!\[CDATA\[|\]\]>", "", svg)
	svg = re.sub(r">\s+", ">", svg)
	svg = re.sub(r"\s+<", "<", svg)
	return re.sub(r"\s{2,}", " ", svg).strip()


def build():
	art = {key: minify((PUBLIC / name).read_text()) for key, name in SOURCES.items()}
	return (
		"/* Generated by tests/tools/build_art.py from public/*.svg. Do not edit. */\n"
		"window.themate = window.themate || {};\n"
		f"window.themate.artSvgs = {json.dumps(art, ensure_ascii=False, indent='\t')};\n"
	)


if __name__ == "__main__":
	text = build()
	if "--check" in sys.argv:
		sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
	OUT.write_text(text)
